namespace OCA\VTramit\Exception;

use OCP\AppFramework\Http;

class InvalidStatusTransitionException extends BaseException {

    public function __contruct(string $message = "", int $code = 0, ?Throwable $previous = null) {
        if (empty($message)) {
            $message = "Cannot transit to the new given status";
        }

        parent::__contruct($message, $code, $previous);
    }

    public function getHttpStatus() {
        return Http::STATUS_NOT_FOUND;
    }
}
